export const eventTypes = [
  "REGISTERED", "NOTICE_PUBLISHED", "FIRST_READING", "SECOND_READING_PASSED", "SECOND_READING_NEGATIVED",
  "COMMITTEE_REFERRED", "HEARING_SCHEDULED", "HEARING_HELD", "COMMITTEE_REPORT_SUBMITTED",
  "COMMITTEE_OF_WHOLE_CONSIDERED", "REPORT_ADOPTED", "THIRD_READING_PASSED", "THIRD_READING_NEGATIVED",
  "TRANSMITTED_TO_OTHER_CHAMBER", "CONCURRENCE_RECORDED", "CONFERENCE_REQUESTED",
  "CONFERENCE_REPORT_ADOPTED", "ENGROSSED", "PRESENTED_FOR_ASSENT", "ASSENT_GRANTED", "ASSENT_WITHHELD",
  "VETO_OVERRIDE_PASSED", "ENACTMENT_VERIFIED", "WITHDRAWN", "LAPSED", "RECOMMITTED",
] as const;

export type LegislativeEvent = (typeof eventTypes)[number];
export type VerificationStatus = "VERIFIED" | "PROVISIONAL" | "UNVERIFIED" | "DISPUTED" | "SUPERSEDED";

const transitions: Partial<Record<LegislativeEvent, readonly LegislativeEvent[]>> = {
  REGISTERED: ["NOTICE_PUBLISHED", "FIRST_READING", "WITHDRAWN", "LAPSED"],
  NOTICE_PUBLISHED: ["FIRST_READING", "WITHDRAWN", "LAPSED"],
  FIRST_READING: ["SECOND_READING_PASSED", "SECOND_READING_NEGATIVED", "WITHDRAWN", "LAPSED"],
  SECOND_READING_PASSED: ["COMMITTEE_REFERRED", "THIRD_READING_PASSED", "RECOMMITTED"],
  SECOND_READING_NEGATIVED: ["RECOMMITTED", "LAPSED"],
  COMMITTEE_REFERRED: ["HEARING_SCHEDULED", "COMMITTEE_REPORT_SUBMITTED", "RECOMMITTED"],
  HEARING_SCHEDULED: ["HEARING_HELD", "RECOMMITTED"],
  HEARING_HELD: ["COMMITTEE_REPORT_SUBMITTED"],
  COMMITTEE_REPORT_SUBMITTED: ["COMMITTEE_OF_WHOLE_CONSIDERED", "REPORT_ADOPTED", "RECOMMITTED"],
  COMMITTEE_OF_WHOLE_CONSIDERED: ["REPORT_ADOPTED", "RECOMMITTED"],
  REPORT_ADOPTED: ["THIRD_READING_PASSED", "THIRD_READING_NEGATIVED", "RECOMMITTED"],
  THIRD_READING_PASSED: ["TRANSMITTED_TO_OTHER_CHAMBER", "ENGROSSED"],
  TRANSMITTED_TO_OTHER_CHAMBER: ["CONCURRENCE_RECORDED", "CONFERENCE_REQUESTED"],
  CONFERENCE_REQUESTED: ["CONFERENCE_REPORT_ADOPTED"],
  CONFERENCE_REPORT_ADOPTED: ["ENGROSSED"],
  CONCURRENCE_RECORDED: ["ENGROSSED"],
  ENGROSSED: ["PRESENTED_FOR_ASSENT"],
  PRESENTED_FOR_ASSENT: ["ASSENT_GRANTED", "ASSENT_WITHHELD"],
  ASSENT_GRANTED: ["ENACTMENT_VERIFIED"],
  ASSENT_WITHHELD: ["VETO_OVERRIDE_PASSED", "LAPSED"],
  VETO_OVERRIDE_PASSED: ["ENACTMENT_VERIFIED"],
};

export function evaluateTransition(from: LegislativeEvent, to: LegislativeEvent, ruleStatus: VerificationStatus, hasEvidence: boolean) {
  if (!transitions[from]?.includes(to)) return { allowed: false, reason: `Transition from ${from} to ${to} is not configured.`, requiresHumanVerification: true };
  const consequential = ["CONCURRENCE_RECORDED", "PRESENTED_FOR_ASSENT", "ASSENT_GRANTED", "VETO_OVERRIDE_PASSED", "ENACTMENT_VERIFIED"].includes(to);
  if (consequential && ruleStatus !== "VERIFIED") return { allowed: false, reason: "A verified legal rule is required for this consequential transition.", requiresHumanVerification: true };
  if (!hasEvidence) return { allowed: false, reason: "Supporting evidence is required for every legislative event.", requiresHumanVerification: true };
  return { allowed: true, requiresHumanVerification: true };
}
